// Pull just the pasteable email copy out of nurture-v2.md.
//
// nurture-v2.md is the source of truth and it is written to be READ: every
// email is followed by the reasoning, the open questions, and what changed
// when. That is the right shape for deciding things and the wrong shape for
// sitting beside a Kit editor at 9am.
//
// So this generates the other shape rather than duplicating the copy by hand.
// Edit nurture-v2.md, re-run this, and the paste file cannot drift out of date
// the way a second hand-maintained copy would.
//
// Run:  node scripts/build-email-paste.mjs

import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'docs/marketing/current-copy/nurture-v2.md'
const OUT = 'docs/marketing/current-copy/nurture-v2-paste.md'

const lines = readFileSync(SRC, 'utf8').split('\n')

const emails = []
let current = null

for (let i = 0; i < lines.length; i += 1) {
  const line = lines[i]

  const header = line.match(/^## (Email \d+ · .+)$/)
  if (header) {
    current = { title: header[1], subject: '', preview: '', body: [] }
    emails.push(current)
    continue
  }
  if (!current) continue

  // A "### " heading ends the email and starts the commentary.
  if (line.startsWith('### ')) {
    current = null
    continue
  }

  if (line.startsWith('**Subject:**')) {
    current.subject = line.replace('**Subject:**', '').trim()
    continue
  }
  if (line.startsWith('**Preview text:**')) {
    current.preview = line.replace('**Preview text:**', '').trim()
    continue
  }

  // The body is fenced by the two --- rules that follow the preview line.
  if (line.trim() === '---') {
    if (current.bodyStarted) current = null
    else current.bodyStarted = true
    continue
  }
  if (current.bodyStarted) current.body.push(line)
}

const out = [
  '# Nurture v2 — paste-ready copy',
  '',
  '**Generated by `scripts/build-email-paste.mjs`. Do not edit this file.**',
  'Edit [nurture-v2.md](nurture-v2.md), which owns the copy and the reasoning,',
  'then re-run the script. This file is the same words with the commentary',
  'stripped out, for sitting beside the Kit editor.',
  '',
  'The link in emails 4 through 8 is already the real one, merge tag included.',
  'Paste it exactly as written.',
  '',
  '---',
  '',
]

for (const e of emails) {
  const body = e.body.join('\n').replace(/\n{3,}/g, '\n\n').trim()
  out.push(`## ${e.title}`, '')
  if (e.subject) out.push(`**Subject line**`, '', '```', e.subject, '```', '')
  if (e.preview) out.push(`**Preview text**`, '', '```', e.preview, '```', '')
  out.push('**Body**', '', body, '', '---', '')
}

writeFileSync(OUT, out.join('\n'), 'utf8')
console.log(`wrote ${OUT} (${emails.length} emails)`)
